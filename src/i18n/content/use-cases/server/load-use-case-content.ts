function assertPublishable(slug: ForContentSlug, locale: ForContentLocale) {
  const route = publication.routes[`/for/${slug}` as keyof typeof publication.routes];
  const localeState = route?.locales[locale as keyof typeof route.locales];
  if (!localeState?.publishable) throw new Error(`Use-case content is not publishable: ${locale}:${slug}`);
}

export async function loadUseCaseContent(slug: ForContentSlug, locale: ForContentLocale): Promise<UseCasePageContent> {
  assertPublishable(slug, locale);
  const contentModule = await contentLoaders[`${locale}:${slug}`]();
  return contentModule.default as UseCasePageContent;
}

export async function loadUseCaseChrome(slug: ForContentSlug, locale: ForContentLocale): Promise<UseCaseChromeMessages> {
  assertPublishable(slug, locale);
  const chromeModule = await chromeLoaders[`${locale}:${slug}`]();
  return chromeModule.default as UseCaseChromeMessages;
}

export async function loadUseCaseRoute(slug: ForContentSlug, locale: ForContentLocale): Promise<UseCaseRouteBundle> {
  const [content, chrome] = await Promise.all([loadUseCaseContent(slug, locale), loadUseCaseChrome(slug, locale)]);
  return { chrome, content };
}
